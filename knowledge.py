def get_collection(reset: bool = False) -> Collection:
    """Отримати колекцію ChromaDB, за потреби -- перестворити її.

    Args:
        reset: Якщо True, спершу видалити існуючу колекцію (використовує
            `main.py seed-kb --reset`).

    Returns:
        Колекція `philosophy_curriculum`, готова до `query()`/`upsert()`.
    """
    client = chromadb.PersistentClient(path=CHROMA_PATH)
    if reset:
        try:
            client.delete_collection(COLLECTION_NAME)
        except Exception:  # noqa: BLE001 -- колекції могло не існувати
            pass
    ef = SentenceTransformerEmbeddingFunction(model_name=EMBEDDING_MODEL)
    return client.get_or_create_collection(COLLECTION_NAME, embedding_function=ef)


def seed_knowledge_base(reset: bool = False) -> int:
    """Наповнити базу знань. Ідемпотентно: повторний виклик нічого не дублює.

    Перевірка ідемпотентності -- лише за кількістю документів. Якщо колись
    зміниться текст KNOWLEDGE_DOCUMENTS, а їхня кількість лишиться тією ж,
    старий вміст не оновиться сам -- знадобиться reset=True.

    Args:
        reset: Передається в get_collection -- перестворити колекцію з нуля
            перед сідом, а не довіряти наявному вмісту.

    Returns:
        Кількість документів у колекції після сіду.
    """
    collection = get_collection(reset=reset)

    if collection.count() == len(KNOWLEDGE_DOCUMENTS):
        return collection.count()

    collection.upsert(
        ids=[doc["id"] for doc in KNOWLEDGE_DOCUMENTS],
        documents=[doc["text"] for doc in KNOWLEDGE_DOCUMENTS],
        metadatas=[{"category": doc["category"]} for doc in KNOWLEDGE_DOCUMENTS],
    )
    return collection.count()


class KnowledgeQuery(BaseModel):
    """Параметри пошуку в базі знань курсу."""

    model_config = ConfigDict(str_strip_whitespace=True)

    query: str = Field(
        description=(
            "Пошуковий запит про методику, регламент або суть течії, "
            "наприклад 'з чого почати стоїцизм' чи 'ліміт бюджету на книги'."
        )
    )
    n_results: int = Field(
        default=3,
        description="Скільки документів повернути, від 1 до 5.",
    )

    @field_validator("query")
    @classmethod
    def query_is_meaningful(cls, v: str) -> str:
        """Запит має бути осмисленим рядком, а не порожнім чи однією літерою.

        Args:
            v: Пошуковий запит.

        Returns:
            Той самий запит, якщо в ньому щонайменше 3 символи.

        Raises:
            ValueError: Запит коротший за 3 символи.
        """
        if len(v) < 3:
            raise ValueError("Запит має містити щонайменше 3 символи")
        return v

    @field_validator("n_results")
    @classmethod
    def n_results_in_range(cls, v: int) -> int:
        """Обмежити кількість результатів розумним діапазоном.

        Args:
            v: Кількість документів.

        Returns:
            Те саме значення, якщо воно в межах 1..5.

        Raises:
            ValueError: Значення поза межами.
        """
        if not 1 <= v <= 5:
            raise ValueError("n_results має бути в межах від 1 до 5")
        return v


@tool(args_schema=KnowledgeQuery)
def search_knowledge(query: str, n_results: int = 3) -> str:
    """Знайти в базі знань курсу методичні правила та опис філософських течій.

    Використовуйте ЛИШЕ для питань про методику самоосвіти, регламент і суть
    течій: «з чого почати вивчення стоїцизму», «який ліміт бюджету на книги»,
    «читати оригінал чи переклад», «коли купувати друковане видання».

    НЕ використовуйте для фактів про конкретних людей, дат життя чи переліку
    творів -- цих даних у базі немає взагалі. Роки життя та течію філософа дає
    find_philosopher, перелік вільних текстів -- find_texts, граф впливів --
    get_influences.

    Приклад: search_knowledge(query="ліміт бюджету на друковані видання").

    Args:
        query: Пошуковий запит українською.
        n_results: Кількість документів (1-5).

    Returns:
        Знайдені документи, розділені рядком '---'.
    """
    collection = get_collection()
    if collection.count() == 0:
        # Захист від забутого `seed-kb`: перший пошук сам наповнює базу.
        seed_knowledge_base()
        collection = get_collection()

    found = collection.query(query_texts=[query], n_results=n_results)
    documents = found["documents"][0]
    if not documents:
        return "База знань не містить відповіді на цей запит."
    return "\n---\n".join(documents)
